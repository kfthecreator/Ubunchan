@pytest.mark.parametrize("cmd", CATASTROPHIC)
def test_catastrophic_commands_are_blocked(cmd):
    verdict = analyze(cmd)
    assert verdict.risk is Risk.BLOCKED, f"{cmd!r} was {verdict.risk.name}: {verdict.reasons}"


@pytest.mark.parametrize("cmd, expected", [
    ("ls -la ~/Downloads", Risk.READ_ONLY),
    ("df -h", Risk.READ_ONLY),
    ("free -h && uname -a", Risk.READ_ONLY),
    ("apt list --installed | grep steam", Risk.READ_ONLY),
    ("apt search blender", Risk.READ_ONLY),
    ("systemctl status bluetooth", Risk.READ_ONLY),
    ("cat /etc/os-release", Risk.READ_ONLY),
    ("find ~/Downloads -name '*.iso'", Risk.READ_ONLY),
    ("sudo apt update", Risk.NORMAL),
    ("sudo apt install -y steam", Risk.NORMAL),
    ("sudo apt update && sudo apt upgrade -y", Risk.NORMAL),
    ("mkdir -p ~/Projects/test", Risk.NORMAL),
    ("snap install spotify", Risk.NORMAL),
    ("echo hello > ~/note.txt", Risk.NORMAL),
    ("sudo systemctl restart bluetooth", Risk.NORMAL),
    ("rm ~/Downloads/old.iso", Risk.DANGEROUS),
    ("rm -rf ~/Downloads/build-tmp", Risk.DANGEROUS),
    ("rm -rf /tmp/mybuild", Risk.DANGEROUS),
    ("sudo apt remove -y vlc", Risk.DANGEROUS),
    ("sudo reboot", Risk.DANGEROUS),
    ("systemctl poweroff", Risk.DANGEROUS),
    ("mv ~/a.txt ~/b.txt", Risk.DANGEROUS),
    ("chmod +x ~/script.sh", Risk.DANGEROUS),
    ("bash ~/install.sh", Risk.DANGEROUS),
    ("sudo apt full-upgrade -y", Risk.DANGEROUS),
])
def test_everyday_commands_are_classified(cmd, expected):
    verdict = analyze(cmd)
    assert verdict.risk is expected, f"{cmd!r}: {verdict.risk.name} {verdict.reasons}"
